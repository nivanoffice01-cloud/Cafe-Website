import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const page = await browser.newPage({ viewport:{width:1440,height:1000} })
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('dialog',d=>d.accept())
try {
  await page.goto('http://127.0.0.1:4187')
  await page.locator('[name=email]').fill('owner@mangosteen.local')
  await page.locator('[name=password]').fill('Mangosteen@123')
  await page.locator('#login-form').evaluate(f=>f.requestSubmit())
  await page.locator('[data-page=waitlist]').first().click()
  await page.locator('[data-waiting-action=add]').first().click()
  const form=page.locator('#waiting-editor')
  await form.locator('[name=name]').fill('Walk-in Browser Guest')
  await form.locator('[name=guests]').fill('3')
  await form.locator('[name=estimatedWait]').fill('20')
  await form.locator('[name=notes]').fill('Prefer a quiet table')
  await page.locator('[form=waiting-editor]').click()
  await page.waitForSelector('#waiting-editor',{state:'detached'})
  assert.match(await page.locator('.waiting-card').first().innerText(),/20 min/)
  await page.locator('.waiting-card [data-waiting-action=edit]').first().click()
  await form.locator('[name=estimatedWait]').fill('25')
  await page.locator('[form=waiting-editor]').click()
  await page.waitForSelector('#waiting-editor',{state:'detached'})
  await page.reload()
  await page.locator('[data-page=waitlist]').first().click()
  assert.match(await page.locator('.waiting-card').first().innerText(),/25 min/)
  await page.screenshot({path:'/tmp/mangosteen-waitlist-desktop.png'})
  await page.locator('[data-waiting-action=call]').first().click()
  await page.waitForFunction(()=>document.querySelector('.waiting-card .floor-badge')?.textContent==='Called')
  await page.locator('[data-waiting-action=seat]').first().click()
  assert.equal(await page.locator('#waiting-seat option[value=R1]').isDisabled(),true)
  await page.locator('#waiting-seat [name=tableId]').selectOption('G1')
  await page.locator('[form=waiting-seat]').click()
  await page.waitForSelector('#waiting-seat',{state:'detached'})
  await page.locator('[data-page=tables]').first().click()
  assert.match(await page.locator('[data-table-id=G1]').innerText(),/Walk-in Browser Guest/)
  assert.equal(await page.locator('[data-table-id=G1]').getAttribute('data-status'),'Occupied')
  await page.locator('[data-page=waitlist]').first().click()
  await page.locator('[data-waiting-action=view][data-view=History]').click()
  assert.match(await page.locator('.waiting-card').innerText(),/Seated/)
  assert.match(await page.locator('.waiting-card').innerText(),/Garden 01/)
  await page.locator('[data-waiting-action=view][data-view=Queue]').click()
  await page.locator('[data-waiting-action=add]').first().click()
  await form.locator('[name=name]').fill('Guest Left Browser')
  await page.locator('[form=waiting-editor]').click()
  await page.waitForSelector('#waiting-editor',{state:'detached'})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=0)
  await page.locator('.crm-mobile-page').selectOption('tables')
  await page.locator('.crm-mobile-page').selectOption('waitlist')
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:'/tmp/mangosteen-waitlist-mobile.png'})
  await page.locator('[data-waiting-action=left]').first().click()
  await page.waitForFunction(()=>!document.querySelector('.waiting-card'))
  await page.locator('[data-waiting-action=view][data-view=History]').click()
  assert.match(await page.locator('.waiting-list').innerText(),/Left/)
  assert.deepEqual(errors,[])
  console.log('Browser passed: add/edit persistence, called, table suitability, seating, live table linkage, history, guest left and mobile navigation.')
} finally { await browser.close() }
