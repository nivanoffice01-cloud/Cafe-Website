  assert.match(await card.innerText(), /Browser QA Guest/)
  assert.equal(await card.getAttribute('data-status'), 'Occupied')
  await card.locator('[data-floor-action=assign]').click()
  await page.locator('[name=waiterId]').selectOption('3')
  await page.locator('[form=table-editor]').click()
  await page.waitForSelector('#table-editor', { state: 'detached' })
  await page.reload()
  await page.locator('[data-page=tables]').first().click()
  card = page.locator('[data-table-id=R3]')
  assert.match(await card.innerText(), /Aman Singh/)
  await card.locator('[data-floor-action=checkout]').click()
  await page.locator('[form=table-editor]').click()
  await page.waitForSelector('#table-editor', { state: 'detached' })
  assert.equal(await card.getAttribute('data-status'), 'Cleaning')
  await card.locator('[data-floor-action=available]').click()
  await page.locator('[form=table-editor]').click()
  await page.waitForSelector('#table-editor', { state: 'detached' })
  assert.equal(await card.getAttribute('data-status'), 'Available')
  await page.screenshot({ path: '/tmp/mangosteen-floor-desktop.png', fullPage: true })
  await page.locator('[data-page=reservations]').first().click()
  await page.locator('[data-floor-action=view][data-id=List]').click()
  assert.match(await page.locator('.data-table').innerText(), /Browser QA Guest/)
  await page.locator('[data-floor-action=new]').click()
  await form.locator('[name=name]').fill('Conflict QA Guest')
  await form.locator('[name=phone]').fill('9876543210')
  await form.locator('[name=tableId]').selectOption('R1')
  await form.locator('[name=status]').selectOption('Confirmed')
