  await page.locator('[data-floor-action=new]').click()
  const form = page.locator('#booking-editor')
  await form.locator('[name=name]').fill('Browser QA Guest')
  await form.locator('[name=phone]').fill('9876543210')
  await form.locator('[name=tableId]').selectOption('R3')
  await form.locator('[name=status]').selectOption('Confirmed')
  await page.locator('[form=booking-editor]').click()
  await page.waitForSelector('#booking-editor', { state: 'detached' })
  await page.locator('.calendar-event').filter({ hasText: 'Browser QA Guest' }).first().click()
  await page.locator('[data-floor-action=status][data-status="Checked in"]').click()
  await page.waitForSelector('.modal', { state: 'detached' })
  await page.locator('[data-page=tables]').first().click()
