import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const base = process.env.REVIEW_URL || 'http://127.0.0.1:5173'
const directory = 'artifacts/reference-experience/local'
await mkdir(directory, { recursive: true })
const browser = await chromium.launch({ headless: true })
const report = { viewportChecks: [], interactions: [], errors: [], brokenResponses: [] }
const mark = label => { report.interactions.push(label); console.log('PASS', label) }
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', error => report.errors.push(error.message))
page.on('response', response => { if (response.status() >= 400) report.brokenResponses.push({ url: response.url(), status: response.status() }) })
try {
  for (const [width,height] of [[320,568],[360,800],[390,844],[768,1024],[1024,768],[1440,1000],[1920,1080]]) {
    await page.setViewportSize({width,height})
    await page.goto(`${base}/reference-experience`)
    await page.waitForTimeout(1300)
    const metrics = await page.evaluate(() => ({width:innerWidth, document:document.documentElement.scrollWidth, brokenImages:[...document.images].filter(i=>i.complete&&!i.naturalWidth).map(i=>i.src)}))
    assert.ok(metrics.document <= width, `Overflow at ${width}`)
    assert.equal(metrics.brokenImages.length,0)
    report.viewportChecks.push({...metrics,height})
    await page.screenshot({path:`${directory}/viewport-${width}.png`})
  }
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`${base}/reference-experience`)
  await page.getByRole('button',{name:'Next dish',exact:true}).click()
  await page.waitForTimeout(1300)
  assert.match(await page.locator('h1').innerText(),/Pesto/)
  await page.getByRole('button',{name:'Previous dish',exact:true}).click()
  await page.waitForTimeout(1300)
  assert.match(await page.locator('h1').innerText(),/Margarita/)
  mark('Forward and reverse table selection')
  await page.mouse.move(850,530); await page.mouse.down(); await page.mouse.move(1110,170,{steps:35}); await page.mouse.up(); await page.waitForTimeout(1100)
  assert.doesNotMatch(await page.locator('h1').innerText(),/Margarita/)
  mark('Pointer drag turns table and updates selected dish')
  const toggle = page.getByRole('switch').first()
  await toggle.click(); assert.equal(await toggle.getAttribute('aria-checked'),'false'); await toggle.click()
  mark('Dish detail switch')
  await page.locator('.ref-glass').scrollIntoViewIfNeeded(); await page.waitForTimeout(700)
  const canvas=page.locator('.ref-glass canvas'), bounds=await canvas.boundingBox()
  const alpha=()=>canvas.evaluate(c=>c.getContext('2d').getImageData(Math.floor(c.width/2),Math.floor(c.height/2),1,1).data[3])
  assert.ok(await alpha()>0)
  await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2)
  assert.equal(await alpha(),0)
  await page.getByRole('button',{name:'Wipe the glass to look inside'}).click()
  assert.match(await canvas.getAttribute('class'),/is-clear/)
  await page.getByRole('button',{name:'Restore the glass'}).click()
  mark('Glass canvas genuinely erases pixels; accessible clear/restore control')
  await page.locator('.ref-card-stage').scrollIntoViewIfNeeded()
  const card=await page.locator('.ref-card-stage').boundingBox()
  await page.mouse.move(card.x+card.width*.8,card.y+card.height*.2);await page.waitForTimeout(700)
  assert.match(await page.locator('.ref-visit-card').evaluate(e=>getComputedStyle(e).transform),/matrix3d/)
  mark('Perspective card tilt')
  await page.locator('.ref-book').scrollIntoViewIfNeeded()
  await page.locator('.ref-book-form fieldset').nth(0).getByRole('button',{name:'4',exact:true}).click()
  await page.locator('.ref-book-form').getByRole('button',{name:'8:00 PM',exact:true}).click()
  await page.getByRole('button',{name:'Choose your seating'}).click()
  assert.equal(await page.locator('.reservation-counter output').innerText(),'4')
  assert.equal(await page.locator('.reservation-times [aria-pressed=true]').innerText(),'8:00 PM')
  await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0)
  mark('Reservation prefill and Escape close; no request submitted')
  await page.setViewportSize({width:390,height:844});await page.goto(`${base}/reference-experience`)
  await page.getByRole('button',{name:'Open navigation'}).click()
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden')
  await page.getByRole('button',{name:'Close navigation'}).focus();await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(()=>document.activeElement.closest('.ref-mobile-nav')!==null),true)
  await page.screenshot({path:`${directory}/mobile-navigation.png`})
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button',{name:'Open navigation'}).evaluate(e=>e===document.activeElement),true)
  assert.notEqual(await page.evaluate(()=>document.body.style.overflow),'hidden')
  mark('Mobile navigation focus containment, Escape, focus and scrolling restoration')
  const touch=await page.context().newCDPSession(page)
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:330,y:570}]})
  for(let x=310;x>=50;x-=20) await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:570}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await page.waitForTimeout(1200)
  assert.doesNotMatch(await page.locator('h1').innerText(),/Margarita/)
  mark('Mobile horizontal touch gesture rotates the table')
  await page.emulateMedia({reducedMotion:'reduce'});await page.reload();await page.waitForTimeout(300)
  assert.equal(await page.locator('.ref-story-line').first().evaluate(e=>getComputedStyle(e).filter),'none')
  mark('Reduced-motion static fallback')
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto(`${base}/menu?table=4`);await page.screenshot({path:`${directory}/approved-menu.png`})
  assert.match(await page.locator('.bm-brand').innerText(),/Table 4/i)
  await page.getByRole('button',{name:'Search menu',exact:true}).click()
  await page.getByRole('textbox',{name:'Search all dishes'}).fill('Margarita')
  await page.locator('.bm-dish-open').filter({hasText:'Margarita'}).click()
  await page.getByRole('button',{name:'Favourite',exact:true}).click()
  await page.getByRole('button',{name:'Close dish details'}).click()
  await page.getByRole('navigation',{name:'Menu navigation'}).getByRole('button',{name:'Favourites',exact:true}).click()
  assert.match(await page.locator('main').innerText(),/Margarita/)
  await page.locator('.bm-dish-open').filter({hasText:'Margarita'}).click()
  await page.getByRole('button',{name:'Add to My List',exact:true}).click()
  await page.getByRole('navigation',{name:'Menu navigation'}).getByRole('button',{name:/My List/}).click()
  assert.match(await page.locator('main').innerText(),/Demo pay & place order/)
  assert.match(await page.locator('main').innerText(),/TABLE 4/)
  mark('Approved menu search, favourites, selection and Table 4 ordering context preserved; no order submitted')
  await page.goto(`${base}/menu/all`)
  assert.match(await page.locator('h1').innerText(),/131/)
  await page.goto(`${base}/menu/browse`)
  await page.locator('.mn-category-grid').waitFor()
  assert.equal(await page.locator('.mn-category-grid>button').count(),15)
  mark('131 dishes and 13 categories retained')
  await page.goto(`${base}/`)
  await page.getByRole('button',{name:/Reserve a table/i}).click()
  assert.equal(await page.locator('.reservation-counter output').innerText(),'2')
  assert.equal(await page.locator('.reservation-times [aria-pressed=true]').innerText(),'7:00 PM')
  await page.keyboard.press('Escape')
  mark('Existing homepage reservation defaults retained')
  assert.deepEqual(report.errors,[])
  assert.deepEqual(report.brokenResponses,[])
} catch(error) {
  report.failure=String(error)
  await page.screenshot({path:`${directory}/failure.png`})
  process.exitCode=1
  console.error(error)
} finally {
  await writeFile(`${directory}/test-results.json`,JSON.stringify(report,null,2))
  await browser.close()
}
