import test from 'node:test'
import assert from 'node:assert/strict'
import { ensureFloor, floorPayload, saveReservation, changeReservation, changeTable, dayInIndia, keepPaidVisit } from './floor.mjs'
const user = { name: 'Test Host' }
const state = () => ensureFloor({ reservations: [], orders: [], staff: [{ id: 1, name: 'Waiter' }] })
const booking = (extra = {}) => ({ name: 'Guest Test', phone: '9876543210', date: dayInIndia(), time: '19:00', guests: 2, tableId: 'R1', duration: 90, status: 'Confirmed', ...extra })

test('capacity, overlapping slots and adjacent bookings', () => {
  const s = state()
  const first = saveReservation(s, booking(), user)
  assert.throws(() => saveReservation(s, booking({ guests: 3 }), user), /seats 2/)
  assert.throws(() => saveReservation(s, booking({ time: '19:30' }), user), /overlaps/)
  assert.equal(saveReservation(s, booking({ time: '20:30' }), user).status, 'Confirmed')
  assert.equal(saveReservation(s, booking({ tableId: 'R2' }), user).status, 'Confirmed')
  assert.equal(first.table, 'Railside 01')
})
test('pending requests do not block; confirmation validates conflicts', () => {
  const s = state()
  saveReservation(s, booking(), user)
  const pending = saveReservation(s, booking({ status: 'Pending' }), user)
  assert.throws(() => changeReservation(s, pending.id, { status: 'Confirmed' }, user), /overlaps/)
  assert.equal(pending.status, 'Pending')
  changeReservation(s, pending.id, { status: 'Cancelled' }, user)
  assert.equal(pending.status, 'Cancelled')
  assert.throws(() => changeReservation(s, pending.id, { status: 'Confirmed' }, user), /Cannot change/)
})
test('rescheduling is atomic and rejects stale revisions', () => {
  const s = state()
  const r = saveReservation(s, booking(), user)
  const other = saveReservation(s, booking({ time: '21:00' }), user)
  assert.throws(() => saveReservation(s, booking({ time: '19:30', revision: other.revision }), user, other.id), /overlaps/)
  assert.equal(other.time, '21:00')
  assert.throws(() => saveReservation(s, booking({ revision: 999 }), user, r.id), /changed/)
  saveReservation(s, booking({ tableId: 'R2', time: '18:15' }), user, r.id)
  assert.equal(r.table, 'Railside 02')
  assert.equal(r.history.length, 2)
})
test('check-in → settle → checkout → cleaning → available', () => {
  const s = state()
  const r = saveReservation(s, booking(), user)
  assert.equal(floorPayload(s).find(t => t.id === 'R1').displayStatus, 'Reserved')
  changeReservation(s, r.id, { status: 'Checked in' }, user)
  const t = s.tables.find(t => t.id === 'R1')
  assert.equal(t.session.guests, 2)
  changeTable(s, 'R1', { action: 'assign', waiterId: '1' }, user)
  s.orders.push({ id: 1, table: 'Railside 01', status: 'Ready', total: 450 })
  assert.equal(floorPayload(s).find(t => t.id === 'R1').runningBill, 450)
  assert.throws(() => changeTable(s, 'R1', { action: 'checkout' }, user), /Settle/)
  s.orders[0].status = 'Paid'
  changeTable(s, 'R1', { action: 'checkout' }, user)
  assert.equal(r.status, 'Completed')
  assert.equal(t.status, 'Cleaning')
  assert.throws(() => changeTable(s, 'R1', { action: 'seat', name: 'Walk In', guests: 2 }, user), /not available/)
  changeTable(s, 'R1', { action: 'available' }, user)
  assert.equal(t.status, 'Available')
})
test('walk-ins persist their party and assigned staff; invalid dates and transitions fail', () => {
  const s = state()
  changeTable(s, 'D1', { action: 'seat', name: 'Walk In', guests: 4 }, user)
  assert.equal(floorPayload(s).find(t => t.id === 'D1').displayStatus, 'Occupied')
  assert.throws(() => changeTable(s, 'D1', { action: 'assign', waiterId: '999' }, user), /staff member/)
  changeTable(s, 'D1', { action: 'checkout' }, user)
  assert.equal(s.tables.find(t => t.id === 'D1').status, 'Cleaning')
  assert.throws(() => saveReservation(s, booking({ time: '25:00' }), user), /valid date/)
  assert.throws(() => saveReservation(s, booking({ date: '2030-02-30' }), user), /valid date/)
  assert.throws(() => saveReservation(s, booking({ status: 'Checked in' }), user), /Pending or Confirmed/)
})
test('existing bookings get table links without changing their details', () => {
  const s = { reservations: [{ id: 1, name: 'Existing', table: 'Canopy 01', date: dayInIndia(), time: '19:00', guests: 6, status: 'Pending' }], staff: [], orders: [] }
  ensureFloor(s)
  assert.equal(s.reservations[0].tableId, 'C1')
  assert.equal(s.reservations[0].duration, 90)
  assert.equal(s.reservations[0].name, 'Existing')
})
test('existing QR table configuration is preserved and normalized without exposing access keys', () => {
  const s = { tables: [{ id: '1', label: 'Table 01', capacity: 2, zoneName: 'Cafe floor', active: true, accessKey: 'private-key' }], reservations: [], orders: [], staff: [] }
  ensureFloor(s)
  const tables = floorPayload(s)
  assert.equal(tables.length, 1)
  assert.equal(tables[0].displayStatus, 'Available')
  assert.equal(tables[0].zone, 'Cafe floor')
  assert.equal(tables[0].accessKey, undefined)
  changeTable(s, '1', { action: 'seat', name: 'Existing Guest', guests: 2 }, user)
  assert.equal(floorPayload(s)[0].displayStatus, 'Occupied')
  assert.equal(s.tables[0].accessKey, 'private-key')
})
test('served prepaid visits show no amount due and can check out; cash settlement retains occupancy', () => {
  const s = state()
  const order = { id: 1, table: 'Table 4', tableCode: '4', status: 'Served', total: 600, paidAt: new Date().toISOString(), createdAt: new Date().toISOString() }
  s.orders.push(order)
  assert.equal(floorPayload(s).find(t => t.id === '4').runningBill, 0)
  changeTable(s, '4', { action: 'checkout' }, user)
  assert.equal(floorPayload(s).find(t => t.id === '4').displayStatus, 'Cleaning')
  changeTable(s, '4', { action: 'available' }, user)
  assert.equal(floorPayload(s).find(t => t.id === '4').displayStatus, 'Available')
  s.orders.push({ id: 2, table: 'Table 4', status: 'Ready', total: 300, createdAt: new Date().toISOString() })
  keepPaidVisit(s, s.orders[1])
  s.orders[1].status = 'Paid'
  assert.equal(floorPayload(s).find(t => t.id === '4').displayStatus, 'Occupied')
  changeTable(s, '4', { action: 'checkout' }, user)
  assert.equal(floorPayload(s).find(t => t.id === '4').displayStatus, 'Cleaning')
})
